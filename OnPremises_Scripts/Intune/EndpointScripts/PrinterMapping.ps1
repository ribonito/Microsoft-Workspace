Write-Output "Running as SYSTEM: $(Test-RunningAsSystem)"

if (-not (Test-RunningAsSystem)) {

    $MappingJson = "$env:APPDATA\Sunrise\PrinterMappings.json"
    if (-not (Test-Path $MappingJson)) {
        Write-Warning "File '$MappingJson' doesn't exist. Printer mapping will not be done."
        Exit 0
    }

    $PrinterMappings = Get-Content -LiteralPath $MappingJson -Raw | ConvertFrom-Json -ErrorAction Stop

    #used to create an array for groups
    $printerMappingConfig = foreach ($d in $($PrinterMappings.Mappings)) {
        [PSCustomObject]@{
            PrintServer = $($d.PrintServer)
            Default     = $($d.Default)
            PrinterName = $($d.PrinterName)
            Id          = $($d.Id)
            GroupFilter = $($d.GroupFilter -split ",")
        }
    }
    Write-Output "Mappings from json: "
    $($printerMappings.Mappings)
    
    # Override with your Active Directory Domain Name e.g. 'ds.nicolonsky.ch' if you haven't configured the domain name as DHCP option
    $searchRoot = ""

    # Get current group membership for the group filter capabilities
    if ($printerMappingConfig.GroupFilter) {
    	try {
    		$groupMemberships = Get-ADGroupMembership -UserPrincipalName $(whoami -upn)
    	}
    	catch {
    		Write-Error $_ -ErrorAction Continue
    	}
    }
}

###########################################################################################
# Mapping network printers
###########################################################################################
#Get PowerShell printers and rename properties

if (-not (Test-RunningAsSystem)) {

	# only map printers where group membership applicable
	$printerMappingConfig = Test-GroupMembership -printerMappingConfig $printerMappingConfig -groupMemberships $groupMemberships

	#iterate through all network printer configuration entries
	foreach ($printer in $printerMappingConfig) {

		Try {
			Write-Output "Get the status of the printer '$($Printer.PrintServer)' on the print server"
			$PrinterServerStatus = (Get-Printer -ComputerName (([URI]($Printer.PrintServer)).host) -Name $Printer.PrinterName).PrinterStatus
			# Only perform check if the printer on the print server is not offline
			If ($PrinterServerStatus -ne "Offline") {
				# Throw error is printer doesn't exist
				If (!(Get-Printer -Name $Printer.PrintServer -ErrorAction SilentlyContinue)){
					Write-Output "Printer not mapped, adding '$($Printer.PrintServer)'"
					Add-Printer -ConnectionName $Printer.PrintServer
					if($Printer.Default -eq 1){
						$printer = Get-CimInstance -Class Win32_Printer -Filter "Name='$($Printer.PrintServer)'"
						Invoke-CimMethod -InputObject $printer -MethodName SetDefaultPrinter
					}
				}
			} else {
				Write-Output "Printer is offline or Sppoler not running"
				$Printer
			}
		} Catch {
			Write-Error "Failed to map the printer $($Printer.PrinterName) - $($Printer.PrintServer)"
			Write-Error $_.Exception.Message
		}
	}
}

